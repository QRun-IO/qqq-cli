import { afterEach, beforeAll, expect, test } from 'bun:test'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { addProfile, bulkLog } from './fake-bulk'
import { command, isolate, press, startTui, waitFor, type Harness } from './helpers'

let h: Harness | undefined
beforeAll(() => isolate())
afterEach(() => {
  h?.store.dispose()
  h?.setup.renderer.destroy()
  h = undefined
})

const key = (k: string, mods?: { ctrl?: boolean; shift?: boolean }) => press(h!, () => h!.setup.mockInput.pressKey(k, mods))
const type = (t: string) => press(h!, () => h!.setup.mockInput.typeText(t))
const enter = () => press(h!, () => h!.setup.mockInput.pressEnter())
const down = () => press(h!, () => h!.setup.mockInput.pressArrow('down'))
const tab = () => press(h!, () => h!.setup.mockInput.pressTab())

test('bulk insert: file, column mapping grid, saved profile, value mapping with the picker, validation, load', async () => {
  const dir = mkdtempSync(join(tmpdir(), 'qqq-bulk-'))
  const file = join(dir, 'b.csv')
  writeFileSync(file, 'name,color\nOne,Red\nTwo,Blue\n')
  h = await startTui(130, 40)
  await command(h, 'table query blk')
  await waitFor(h, (x) => x.includes('2 records'))
  await key('a')
  await type('Bulk insert from')
  await enter()
  await waitFor(h, (x) => x.includes('the file to load'))
  await tab()
  await key('u', { ctrl: true })
  await type(file)
  await enter()
  let f = await waitFor(h, (x) => x.includes('Loaded from') && x.includes('column name'))
  expect(f).toContain('Color')
  await down()
  await enter()
  await waitFor(h, (x) => x.includes('Color: load from'))
  await down()
  await enter()
  await waitFor(h, (x) => x.includes('column color'))
  await enter()
  await waitFor(h, (x) => x.includes('Map file values'))
  await type('Map file')
  await enter()
  await waitFor(h, (x) => x.includes('[map values]'))
  await key('P')
  await waitFor(h, (x) => x.includes('Saved bulk load profiles'))
  await type('Save this')
  await enter()
  await waitFor(h, (x) => x.includes('Save the mapping as'))
  await type('Mine')
  await enter()
  await waitFor(h, (x) => x.includes('saved Mine'))
  expect(bulkLog().length).toBe(1)
  await key('s', { ctrl: true })
  f = await waitFor(h, (x) => x.includes('In the file') && x.includes('(not mapped)'))
  await enter()
  await waitFor(h, (x) => x.includes('Choose Color'))
  await enter()
  await waitFor(h, (x) => x.includes('Red (1)'))
  await down()
  await enter()
  await waitFor(h, (x) => x.includes('Choose Color'))
  await key('u', { ctrl: true })
  await type('Blu')
  await waitFor(h, (x) => x.includes('║ Blue'))
  await enter()
  await waitFor(h, (x) => x.includes('Blue (2)'))
  await key('s', { ctrl: true })
  await waitFor(h, (x) => x.includes('Validate every record first'))
  await key('v')
  await waitFor(h, (x) => x.includes('will be inserted') && !x.includes('Validate every record first'))
  await key('s', { ctrl: true })
  await key('y')
  await waitFor(h, (x) => x.includes('Blk records were inserted'))
  const mapping = h.log.requests.find((r) => /\/bi\/step\/fileMapping$/.test(r.path))!
  expect(String((mapping.body as Record<string, string>).values)).toContain('fieldListJSON')
  const valueStep = h.log.requests.find((r) => /\/bi\/step\/valueMapping$/.test(r.path))!
  expect(String((valueStep.body as Record<string, string>).values)).toContain('"mappedValuesJSON":"{\\"Red\\":1,\\"Blue\\":2}"')
})

test('bulk edit switches on fields and sends them with the selection; bulk delete reviews and deletes', async () => {
  h = await startTui(130, 40)
  await command(h, 'table query blk')
  await waitFor(h, (x) => x.includes('2 records'))
  await key(' ')
  await key('a')
  await type('Bulk edit')
  await enter()
  await waitFor(h, (x) => x.includes('Switch on the fields'))
  await key('s', { ctrl: true })
  await waitFor(h, (x) => x.includes('switch on at least one field'))
  await enter()
  await type('Renamed')
  await enter()
  await waitFor(h, (x) => x.includes('[x] Name') && x.includes('Renamed'))
  await key('s', { ctrl: true })
  await waitFor(h, (x) => x.includes('Update the records now'))
  await key('s', { ctrl: true })
  await key('y')
  await waitFor(h, (x) => x.includes('Blk records were edited'))
  const init = h.log.requests.find((r) => r.path === '/processes/blk.bulkEdit/init')!
  expect(JSON.stringify(init.body)).toContain('recordIds')
  const edit = h.log.requests.find((r) => /\/be\/step\/edit$/.test(r.path))!
  expect(String((edit.body as Record<string, string>).values)).toContain('"bulkEditEnabledFields":"name"')
  await press(h!, () => h!.setup.mockInput.pressEscape())
  await key('a')
  await type('Bulk delete')
  await enter()
  await waitFor(h, (x) => x.includes('Delete the records now'))
  await key('s', { ctrl: true })
  await key('y')
  await waitFor(h, (x) => x.includes('Blk records were deleted'))
})



