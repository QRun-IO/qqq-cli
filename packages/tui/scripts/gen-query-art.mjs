// Generates the screen saver's Query art (src/saver/query-art.ts: LARGE, MEDIUM, SMALL and the dot
// boxes of the eye and the tail) from Query's own drawing: the inline SVG on https://www.qrun.io/query/
// (viewBox 0 0 331.41 348.44; the first path is the sitting dog, the second his eye). Needs `inkscape`
// and ImageMagick (`magick`) on the PATH; run by hand when the drawing changes:
//   node scripts/gen-query-art.mjs query-hero.svg [outdir]
// Each size is the drawing rasterised at 8× the dot grid, averaged down to it (a box filter, so a thin
// stroke keeps its weight as coverage) and thresholded per size (thinner strokes need a lower cut).
import { execFileSync } from 'node:child_process'
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

const [svgPath, outDir = '.'] = process.argv.slice(2)
if (!svgPath) throw new Error('usage: gen-query-art.mjs query-hero.svg [outdir]')
const svg = readFileSync(svgPath, 'utf8').replaceAll('currentColor', '#ffffff')
const paths = [...svg.matchAll(/<path[^>]*>/g)].map((m) => m[0])
const wrap = (body) => `<svg viewBox="0 0 331.41 348.44" xmlns="http://www.w3.org/2000/svg"><rect width="331.41" height="348.44" fill="#000"/>${body}</svg>`
const work = mkdtempSync(join(tmpdir(), 'query-art-'))

/** Coverage 0…1 per dot of an SVG body, on a grid of w×h dots. */
function raster(body, w, h) {
  const file = join(work, 'in.svg')
  writeFileSync(file, wrap(body))
  const png = join(work, 'out.png')
  execFileSync('inkscape', [file, '-o', png, '-w', String(w * 8), '-h', String(h * 8)], { stdio: 'ignore' })
  const raw = execFileSync('magick', [png, '-colorspace', 'Gray', '-filter', 'Box', '-resize', `${w}x${h}!`, '-depth', '8', 'gray:-'], { maxBuffer: 1 << 24 })
  return Array.from({ length: h }, (_, y) => Array.from({ length: w }, (_, x) => raw[y * w + x] / 255))
}

const DOT = [[0x01, 0x02, 0x04, 0x40], [0x08, 0x10, 0x20, 0x80]]
function braille(bits) {
  const rows = []
  for (let cy = 0; cy < bits.length / 4; cy++) {
    let line = ''
    for (let cx = 0; cx < bits[0].length / 2; cx++) {
      let code = 0
      for (let dx = 0; dx < 2; dx++) for (let dy = 0; dy < 4; dy++) if (bits[cy * 4 + dy]?.[cx * 2 + dx]) code |= DOT[dx][dy]
      line += code ? String.fromCodePoint(0x2800 + code) : ' '
    }
    rows.push(line)
  }
  return rows
}

const SIZES = { large: { w: 42, h: 22, cut: 0.42 }, medium: { w: 25, h: 13, cut: 0.28 }, small: { w: 17, h: 9, cut: 0.2 } }
const out = {}
for (const [name, { w, h, cut }] of Object.entries(SIZES)) {
  const dw = w * 2
  const dh = h * 4
  const bits = raster(paths[0], dw, dh).map((r) => r.map((v) => v >= cut))
  // his eye: the second path alone, any coverage at all
  const eyeCov = raster(paths[1], dw, dh)
  const eyeDots = []
  eyeCov.forEach((r, y) => r.forEach((v, x) => { if (v >= 0.12) eyeDots.push([x, y]) }))
  const eye = eyeDots.length ? [Math.min(...eyeDots.map((d) => d[0])), Math.min(...eyeDots.map((d) => d[1])), Math.max(...eyeDots.map((d) => d[0])), Math.max(...eyeDots.map((d) => d[1]))] : [0, 0, 0, 0]
  // the eye is part of the dog path's raster too: keep the eye dots drawn
  for (const [x, y] of eyeDots) bits[y][x] = true
  // the tail: the low left corner of the drawing
  const tail = [0, Math.round(dh * 0.62), Math.round(dw * 0.2), dh - 1]
  out[name] = { rows: braille(bits), eye, tail, w, h }
}
const ts = Object.entries(out).map(([name, o]) => `/** ${name} Query, ${o.w}×${o.h} cells, facing right (generated by scripts/gen-query-art.mjs). */\nconst ${name.toUpperCase()} = [\n${o.rows.map((r) => `  ${JSON.stringify(r)},`).join('\n')}\n]\n`).join('\n')
const parts = `const PARTS: Record<QuerySize, Parts> = {\n${Object.entries(out).map(([n, o]) => `  ${n}: { eye: [${o.eye}], tail: [${o.tail}] },`).join('\n')}\n}\n`
writeFileSync(join(outDir, 'query-art.generated.txt'), `${ts}\n${parts}`)
for (const [n, o] of Object.entries(out)) console.log(`--- ${n} ${o.w}x${o.h} eye ${o.eye} tail ${o.tail}\n${o.rows.join('\n')}`)
